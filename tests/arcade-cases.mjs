assert.equal(doc.getElementById('book-game-title').textContent,memory.name);
assert.equal(doc.getElementById('book-next'),null);
doc.getElementById('book-close').click();
assert.deepEqual(launched,[]);
win.matchMedia=()=>({matches:false});
reader.open(maze,tile,slot);reader.open(memory,tile,slot);
assert.equal(dialog.open,true);
assert.equal(doc.getElementById('book-game-title').textContent,maze.name);
