import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
import {createCaseReader} from '../public/arcade-cases.js';
import {coverMarkup} from '../public/arcade-library.js';
import {GAMES} from '../public/arcade-data.js';
const html=readFileSync(new URL('../app/family/arcade/route.ts',import.meta.url),'utf8').split('const html=`')[1].split('`;')[0];
const dom=new JSDOM(html,{url:'https://example.test/family/arcade',pretendToBeVisual:true}),doc=dom.window.document,win=dom.window;
const dialog=doc.getElementById('arcade-book');
dialog.showModal=()=>{dialog.open=true;};dialog.close=()=>{dialog.open=false;dialog.dispatchEvent(new win.Event('close'));};
win.matchMedia=()=>({matches:true});
const launched=[];
const reader=createCaseReader({document:doc,coverMarkup,onPlay:id=>launched.push(id),players:()=>['Dad','Harper & Chloe'],getAudioContext:()=>null});
const slot=doc.createElement('div'),tile=doc.createElement('button');slot.append(tile);doc.body.append(slot);
const memory=GAMES.find(g=>g.id==='memory'),maze=GAMES.find(g=>g.id==='maze');
reader.open(memory,tile,slot);
assert.equal(dialog.open,true);assert.equal(doc.getElementById('book-game-rules').textContent,memory.description);
assert.equal(doc.getElementById('book-page-number').textContent,'1 / 2');assert.equal(launched.length,0,'Reading instructions never starts a game');
doc.getElementById('book-next').click();assert.equal(doc.getElementById('book-page-number').textContent,'2 / 2');assert.equal(doc.getElementById('book-player-two').textContent,'Harper & Chloe');
doc.getElementById('book-prev').click();assert.equal(doc.getElementById('book-game-rules').textContent,memory.description);
doc.getElementById('book-back').click();assert.equal(dialog.open,false);assert.equal(launched.length,0);
reader.open(maze,tile,slot);assert.equal(doc.getElementById('book-page-number').textContent,'1 / 2');doc.getElementById('book-play').click();doc.getElementById('book-play').click();assert.deepEqual(launched,['maze']);
assert.equal(doc.querySelector('.book-flight'),null,'Reduced motion opens immediately');
win.matchMedia=()=>({matches:false});let finish;win.Element.prototype.animate=()=>({finished:new Promise(resolve=>{finish=resolve;})});
reader.open(memory,tile,slot);reader.open(maze,tile,slot);assert.equal(doc.querySelectorAll('.book-flight').length,1,'Repeated taps cannot duplicate flight or selection');
finish();await Promise.resolve();assert.equal(doc.querySelector('.book-flight'),null);assert.equal(dialog.open,true);assert.equal(doc.getElementById('book-game-title').textContent,memory.name);assert.equal(tile.hasAttribute('aria-busy'),false);
doc.getElementById('book-close').click();
doc.getElementById('cabinet-fx').click();assert.equal(win.localStorage.getItem('avk:case-fx'),'off');
console.log('PASS: case pickup, page turns, correct rules and roster, cancellation, launch once, reduced motion, repeated taps, and sound preference.');
win.close();
