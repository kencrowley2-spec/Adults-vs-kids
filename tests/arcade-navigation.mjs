import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const html=read('app/family/arcade/route.ts').split('const html=`')[1].split('`;')[0];
const dom=new JSDOM(html,{runScripts:'outside-only',url:'https://adultsvskids.com/family/arcade'});
const {window}=dom,{document}=window;
window.HTMLDialogElement.prototype.showModal=function(){this.open=true};
window.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new window.Event('close'))};
window.eval(read('public/family-tools.js'));
window.eval(read('public/arcade-navigation.js'));
const $=id=>document.getElementById(id);
const tabs=document.querySelector('.arcade-tabs');
assert.equal(tabs.querySelectorAll('a,button').length,5);
const arcadeLinks=[...tabs.querySelectorAll('.arcade-tabs-inner > a')];
assert.deepEqual(arcadeLinks.slice(0,2).map(a=>a.textContent.trim()),['Home','Arcade']);
assert.equal(arcadeLinks[0].getAttribute('href'),'/family');
assert.equal(arcadeLinks[1].getAttribute('aria-current'),'page');
const dashboardHtml=read('lib/family-dashboard.ts');
const dashboardTabs=new JSDOM(dashboardHtml.slice(dashboardHtml.indexOf('<nav class="dashboard-tabs"'),dashboardHtml.indexOf('</nav>',dashboardHtml.indexOf('<nav class="dashboard-tabs"'))+6)).window.document;
const dashboardLinks=[...dashboardTabs.querySelectorAll('.dashboard-tabs-inner > a')];
assert.deepEqual(dashboardLinks.slice(0,2).map(a=>a.textContent.trim()),['Home','Arcade']);
assert.deepEqual(dashboardLinks.slice(0,2).map(a=>a.getAttribute('href')),['/family','/family/arcade']);
assert.equal(dashboardLinks[0].getAttribute('aria-current'),'page');

assert.equal(tabs.querySelector('[aria-current=page]').textContent.trim(),'Arcade');
assert.equal(tabs.querySelector('a[href="/family/leaderboard"]').textContent.trim(),'Leaderboard');
let opened=0,closed=0,random=0;
window.addEventListener('arcade-overlay-open',()=>opened++);
window.addEventListener('arcade-overlay-close',()=>closed++);
$('arcade-random').addEventListener('click',()=>random++);
const toolButton=tabs.querySelector('[data-arcade-tools]');
toolButton.click();assert.equal($('memberDialog').open,true);
assert.equal($('showdownRound').textContent,'ROUND 1 OF 12');
document.querySelector('[data-showdown-team="0"][data-delta="1"]').click();
assert.equal($('showdownScore0').textContent,'1');
$('showdownNext').click();assert.equal($('showdownRound').textContent,'ROUND 2 OF 12');
document.querySelector('[data-arcade-tools-close]').click();assert.equal($('memberDialog').open,false);
toolButton.click();assert.equal($('showdownScore0').textContent,'1');assert.equal($('showdownRound').textContent,'ROUND 2 OF 12');
$('memberDialog').close();
$('arcade-more-toggle').click();assert.equal($('arcade-more').open,true);assert.equal($('arcade-more-toggle').getAttribute('aria-expanded'),'true');
$('arcade-menu-random').click();assert.equal(random,1);assert.equal($('arcade-more').open,false);assert.equal($('arcade-more-toggle').getAttribute('aria-expanded'),'false');
$('arcade-more-toggle').click();document.querySelector('[data-close-arcade-menu]').click();assert.equal($('arcade-more').open,false);
assert.equal(opened,4);assert.equal(closed,4);
console.log('PASS: five Arcade tabs, direct family tools, 12-round navigation, persistent tool scores, modal close, More menu, and random challenge launch.');
dom.window.close();
